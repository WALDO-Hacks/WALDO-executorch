#!/usr/bin/env python3
"""Export WALDO's object detector (YOLOv8n, 28 classes, yolo.py) for the Ethos-U85.

    <venv with ultralytics>/bin/python model/yolo/export_yolo.py cmsis-executorch.cbuild-mlops.yml <calib image dir>

Same flow and NPU/Vela settings as the face and keyword models: int8 PT2E with the
EthosUQuantizer, calibrated on letterboxed photos (e.g. COCO128's 128 images), delegated to
the Ethos-U, written as model/yolo/yolo.pte (+ src/yolo_pte.c with --c-array).
"""
import re
import sys
from pathlib import Path

import numpy as np
import torch
import yaml
from PIL import Image

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path[:0] = [str(HERE), str(ROOT)]

from create_ai_layer import compile_spec  # noqa: E402
from yolo import IMGSZ, RawYolo  # noqa: E402


def letterbox(path):
    im = Image.open(path).convert("RGB")
    s = IMGSZ / max(im.size)
    im = im.resize((round(im.width * s), round(im.height * s)), Image.BILINEAR)
    canvas = np.full((IMGSZ, IMGSZ, 3), 114, np.uint8)
    y, x = (IMGSZ - im.height) // 2, (IMGSZ - im.width) // 2
    canvas[y:y + im.height, x:x + im.width] = np.asarray(im)
    return torch.from_numpy(canvas).permute(2, 0, 1)[None].float() / 255


def main():
    from executorch.backends.arm.ethosu import EthosUPartitioner
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_quantization_config
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e

    mlops_file = Path(sys.argv[1]).resolve()
    spec = compile_spec(yaml.safe_load(mlops_file.read_text())["cbuild-mlops"], mlops_file.parent)
    imgs = sorted(p for p in Path(sys.argv[2]).iterdir() if p.suffix.lower() in {".jpg", ".jpeg", ".png"})
    print(f"[yolo] {len(imgs)} calibration images")

    model = RawYolo().eval()
    example = (torch.zeros(1, 3, IMGSZ, IMGSZ),)
    quantizer = EthosUQuantizer(spec)
    quantizer.set_global(get_symmetric_quantization_config(is_per_channel=True))
    prepared = prepare_pt2e(torch.export.export(model, example).module(), quantizer)
    with torch.no_grad():
        for p in imgs:
            prepared(letterbox(p))
    quantized = convert_pt2e(prepared)
    torch.save(quantized, HERE / "yolo_int8_host.pt") if "--save-host" in sys.argv else None

    edge = to_edge_transform_and_lower(
        torch.export.export(quantized, example),
        partitioner=[EthosUPartitioner(spec)],
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    )
    pte = bytes(edge.to_executorch(ExecutorchBackendConfig(extract_delegate_segments=False)).buffer)
    (HERE / "yolo.pte").write_bytes(pte)
    ops = sorted(set(re.findall(rb"(?:aten|quantized_decomposed|cortex_m)::\w+", pte)))
    print(f"[yolo] {len(pte)} byte program, operators outside the NPU delegate: {[o.decode() for o in ops]}")
    if "--c-array" in sys.argv:
        rows = [", ".join(f"0x{b:02x}" for b in pte[i:i + 16]) for i in range(0, len(pte), 16)]
        (ROOT / "src" / "yolo_pte.c").write_text(
            "// Generated by model/yolo/export_yolo.py -- do not edit. YOLOv8n: AGPL-3.0 (Ultralytics).\n"
            "__attribute__((aligned(64))) const unsigned char yolo_pte[] = {\n  "
            + ",\n  ".join(rows) + "\n};\nconst unsigned long yolo_pte_size = sizeof(yolo_pte);\n")


if __name__ == "__main__":
    main()
