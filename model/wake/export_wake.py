#!/usr/bin/env python3
"""Export the wake-word network for the M55-HE's Ethos-U55-128 (same flow as model/kws/export_kws.py --he).

    python -I model/wake/export_wake.py w32b4_s1          (run from the repo root)

PT2E int8 (per-channel symmetric, calibrated on augmented real Speech Commands speech and
TTS "Hey Waldo" windows from the TRAIN voices), delegated to the Ethos-U55. Writes
he/wake_pte_he.c (symbol wake_pte), he/test_wake.h (boot self-test: one held-out-voice
VALIDATION positive and the KWS "yes" as a known negative) and <runs>/<run>/wake_he.pte.
Prints float-vs-int8 agreement on validation windows. The test split is never read.
"""
import argparse
import logging
import sys
from pathlib import Path

import numpy as np
import torch
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path[:0] = [str(HERE), str(ROOT)]

import synth  # noqa: E402
import wakelib  # noqa: E402

MLOPS = ROOT / "cmsis-executorch.cbuild-mlops.yml"


def he_spec():
    """EthosUCompileSpec for the HE's U55-128 (as export_kws.py --he)."""
    from create_ai_layer import compile_spec
    mlops = yaml.safe_load(MLOPS.read_text())["cbuild-mlops"]
    mlops = {**mlops, "npu": {"type": "Ethos-U55", "macs": 128},
             "vela": {**mlops.get("vela", {}), "options": "--accelerator-config ethos-u55-128 "
                      "--system-config RTSS_HE_SRAM_MRAM --memory-mode Shared_Sram"}}
    return compile_spec(mlops, MLOPS.parent)


def calibration_inputs(cfg, n=600, seed=0):
    """(n, 49, 10, 1) MFCC windows: speech-like data the deployed model will see."""
    rng = np.random.default_rng(seed)
    corpus = synth.Corpus(cfg, "train")
    audio, _ = synth.training_batch(corpus, rng, n // 3, cfg["train"]["neg_ratio"], 2.0)
    return torch.from_numpy(wakelib.mfcc_batch(np.round(audio).astype(np.int16))).unsqueeze(-1)


def build_quantized(model, cfg):
    """PT2E int8 module (simulated quantisation, not the NPU) of a trained float WakeNet."""
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_quantization_config
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e
    deploy = model.deploy()
    samples = calibration_inputs(cfg)
    quantizer = EthosUQuantizer(he_spec())
    quantizer.set_global(get_symmetric_quantization_config(is_per_channel=True))
    prepared = prepare_pt2e(torch.export.export(deploy, (samples[:1],)).module(), quantizer)
    with torch.no_grad():
        for s in samples:
            prepared(s[None])
    return convert_pt2e(prepared)


def c_array(name, pte, comment):
    rows = [", ".join(f"0x{b:02x}" for b in pte[i:i + 16]) for i in range(0, len(pte), 16)]
    return (f"// Generated by model/wake/export_wake.py -- do not edit. {comment}\n"
            f"__attribute__((aligned(16))) const unsigned char {name}[] = {{\n  " + ",\n  ".join(rows)
            + f"\n}};\nconst unsigned long {name}_size = sizeof({name});\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("run")
    args = ap.parse_args()
    logging.basicConfig(level=logging.INFO)
    from evaluate import load_float
    from executorch.backends.arm.ethosu import EthosUPartitioner
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower

    cfg = wakelib.load_config()
    run = Path(cfg["paths"]["runs"]) / args.run
    model = load_float(run)
    deploy = model.deploy()
    quant = build_quantized(model, cfg)

    # float vs folded vs int8 on validation windows (train.val_set recipe, different seed)
    val = synth.Corpus(cfg, "val")
    rng = np.random.default_rng(7)
    audio, y = synth.training_batch(val, rng, 800, cfg["train"]["neg_ratio"], 2.0)
    x = torch.from_numpy(wakelib.mfcc_batch(np.round(audio).astype(np.int16))).unsqueeze(-1)
    with torch.no_grad():
        pf = torch.softmax(model(x), 1)[:, 1].numpy()
        pd = torch.softmax(deploy(x), 1)[:, 1].numpy()
        pq = np.concatenate([torch.softmax(quant(x[i:i + 1]), 1)[:, 1].numpy() for i in range(len(x))])
    thr = 0.5
    print(f"[wake] BN fold: max |float - folded| posterior {np.abs(pf - pd).max():.2e}")
    print(f"[wake] int8 vs float on {len(x)} validation windows: mean |dp| {np.abs(pf - pq).mean():.4f}, "
          f"max {np.abs(pf - pq).max():.3f}, decision agreement at {thr}: {((pf >= thr) == (pq >= thr)).mean():.4f}, "
          f"at 0.9: {((pf >= 0.9) == (pq >= 0.9)).mean():.4f}; correlation {np.corrcoef(pf, pq)[0, 1]:.4f}")

    edge = to_edge_transform_and_lower(
        torch.export.export(quant, (x[:1],)),
        partitioner=[EthosUPartitioner(he_spec())],
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    )
    pte = bytes(edge.to_executorch(ExecutorchBackendConfig(extract_delegate_segments=False)).buffer)
    (run / "wake_he.pte").write_bytes(pte)
    (ROOT / "he" / "wake_pte_he.c").write_text(c_array("wake_pte", pte, "Hey Waldo detector for the Ethos-U55-128."))
    import re
    ops = sorted(set(re.findall(rb"(?:aten|quantized_decomposed|cortex_m)::\w+", pte)))
    print(f"[wake] {len(pte)} byte program, operators named outside the NPU delegate: {[o.decode() for o in ops]}")

    # boot self-test: a validation-voice positive (clean, centred) and the KWS "yes" as negative
    clip = val.tts["pos"][0]
    win = np.zeros(wakelib.WINDOW, np.float32)
    s = (wakelib.WINDOW - len(clip)) // 2
    win[s:s + len(clip)] = clip * (0.5 * 32767 / np.abs(clip).max())
    win = np.round(win).astype(np.int16)
    with torch.no_grad():
        p_pos = float(torch.softmax(model(torch.from_numpy(wakelib.mfcc_batch(win[None])).unsqueeze(-1)), 1)[0, 1])
        yes = wakelib.kws_mfcc.read_wav(ROOT / "model" / "kws" / "yes.wav")[:wakelib.WINDOW]
        p_neg = float(torch.softmax(model(torch.from_numpy(wakelib.mfcc_batch(yes[None])).unsqueeze(-1)), 1)[0, 1])
    print(f"[wake] self-test window: float wake posterior {p_pos:.4f}; KWS 'yes' {p_neg:.4f}")
    (ROOT / "he" / "test_wake.h").write_text(
        "// Generated by model/wake/export_wake.py -- do not edit.\n"
        "// One VALIDATION-voice macOS TTS \"Hey Waldo\" (peak-normalised, centred in 1 s; macOS TTS output).\n"
        "#pragma once\n#include <stdint.h>\n"
        f"static const float test_wake_float_prob = {p_pos:.6g}f;   // float model, host\n"
        f"static const int16_t test_wake_pos[{len(win)}] = {{\n"
        + ",\n".join(", ".join(str(v) for v in win[i:i + 16]) for i in range(0, len(win), 16)) + "};\n")
    print(f"[wake] wrote he/wake_pte_he.c, he/test_wake.h, {run}/wake_he.pte")


if __name__ == "__main__":
    main()
