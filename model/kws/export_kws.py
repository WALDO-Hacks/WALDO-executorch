#!/usr/bin/env python3
"""Export WALDO's keyword spotter for the Ethos-U85 (and the HE's Ethos-U55-128).

    # KWS v2 (kws_vocab.py; weights from kws2_train.py):
    .venv/bin/python model/kws/export_kws.py cmsis-executorch.cbuild-mlops.yml --weights K/runs/r1/best.npz --calib K/feats/val.npz
    .venv/bin/python model/kws/export_kws.py cmsis-executorch.cbuild-mlops.yml --weights ... --calib ... --he
    # Arm's MicroNet-M, the fallback (WALDO_KWS_MICRONET in src/kws_model.h):
    .venv/bin/python model/kws/export_kws.py cmsis-executorch.cbuild-mlops.yml --micronet [--he]

--he: the same model for the M55-HE's Ethos-U55-128 (two-brain build), written to
he/kws_pte_he.c only (same symbol, kws_pte; the HE image links it instead).
--disable w1,w2 / --threshold w=0.85,...: per-word switches in src/kws_labels.h (a word that
failed its test stays in the model but is never reported). Every run rewrites src/kws_labels.h.

The face model goes through create_ai_layer.py; this is the same flow for the second
model, with the same NPU and Vela settings (read from the cbuild-mlops.yml): quantize to
int8 with MFCCs of real speech as calibration data, delegate to the Ethos-U, write
src/kws_pte.c/.h (the program as a C array, symbol kws_pte) and model/kws/kws.pte.
It also checks the quantized model against the float one on the sample recordings.
"""
import sys
from pathlib import Path

import numpy as np
import torch
import yaml

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path[:0] = [str(HERE), str(ROOT)]

import mfcc  # noqa: E402
import kws_vocab  # noqa: E402
from micronet import LABELS as MICRONET_LABELS, MicroNetM  # noqa: E402
from create_ai_layer import compile_spec  # noqa: E402

LABELS = MICRONET_LABELS

SAMPLES = ["yes", "down", "right_left_up", "yes_no_go_stop"]


def calibration_inputs():
    """1 s windows of the sample words at a few gains and offsets, plus noise and silence."""
    rng = np.random.default_rng(0)
    clips = []
    for name in SAMPLES:
        audio = mfcc.read_wav(HERE / f"{name}.wav")
        for step in (8000, 4000):
            clips += mfcc.windows(audio, step)
    out = []
    for c in clips:
        for gain in (0.25, 1.0, 2.0):
            x = np.clip(c.astype(np.float32) * gain + rng.normal(0, 30, c.shape), -32768, 32767)
            out.append(x.astype(np.int16))
    for level in (5, 50, 500):   # room noise and silence
        out.append(rng.normal(0, level, mfcc.WINDOW).clip(-32768, 32767).astype(np.int16))
    return [torch.from_numpy(mfcc.mfcc(a)).reshape(1, 49, 10, 1) for a in out]


def label(logits):
    p = torch.softmax(logits.flatten(), 0)
    return f"{LABELS[int(p.argmax())]}:{float(p.max()):.2f}"


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


def labels_header(disable, thresholds):
    def names(ls):
        return "{" + ", ".join(f'"{l}"' for l in ls) + "}"

    def arr(vals):
        return "{" + ", ".join(str(v) for v in vals) + "}"
    v2 = kws_vocab.LABELS
    en = [0 if l in disable else 1 for l in v2]
    th = [round(100 * thresholds.get(l, 0.80)) for l in v2]
    m = MICRONET_LABELS
    return (
        "// Generated by model/kws/export_kws.py from model/kws/kws_vocab.py -- do not edit.\n"
        "// Keyword labels in model output order; _silence_ and _unknown_ last.\n"
        "#pragma once\n#include \"kws_model.h\"\n\n#ifdef WALDO_KWS_MICRONET\n"
        f"#define KWS_LABELS {len(m)}\n#define KWS_WORDS {len(m) - 2}\n"
        f"#define KWS_LABEL_NAMES {names(m)}\n"
        f"#define KWS_LABEL_ENABLED {arr([1] * len(m))}\n"
        f"#define KWS_LABEL_THRESHOLD_PCT {arr([80] * len(m))}\n"
        "#else\n"
        f"#define KWS_LABELS {len(v2)}\n#define KWS_WORDS {kws_vocab.WORDS}\n"
        f"#define KWS_LABEL_NAMES {names(v2)}\n"
        f"#define KWS_LABEL_ENABLED {arr(en)}\n"
        f"#define KWS_LABEL_THRESHOLD_PCT {arr(th)}\n"
        "#endif\n")


def main():
    global LABELS
    from executorch.backends.arm.ethosu import EthosUPartitioner
    from executorch.backends.arm.quantizer import EthosUQuantizer, get_symmetric_quantization_config
    from executorch.exir import EdgeCompileConfig, ExecutorchBackendConfig, to_edge_transform_and_lower
    from torchao.quantization.pt2e.quantize_pt2e import convert_pt2e, prepare_pt2e

    mlops_file = Path(sys.argv[1]).resolve()
    he = "--he" in sys.argv[2:]
    mlops = yaml.safe_load(mlops_file.read_text())["cbuild-mlops"]
    if he:   # the HE core's NPU and its Vela system configuration (.cmsis/ensemble_vela.ini)
        mlops = {**mlops, "npu": {"type": "Ethos-U55", "macs": 128},
                 "vela": {**mlops.get("vela", {}), "options": "--accelerator-config ethos-u55-128 "
                          "--system-config RTSS_HE_SRAM_MRAM --memory-mode Shared_Sram"}}
    spec = compile_spec(mlops, mlops_file.parent)

    disable = set(filter(None, (arg("--disable") or "").split(",")))
    thresholds = {kv.split("=")[0]: float(kv.split("=")[1]) for kv in filter(None, (arg("--threshold") or "").split(","))}
    (ROOT / "src" / "kws_labels.h").write_text(labels_header(disable, thresholds))
    legacy = "--micronet" in sys.argv
    if legacy:
        model = MicroNetM().eval()
    else:
        import kws2_train
        model = kws2_train.build(Path(arg("--weights"))).eval()
        LABELS = kws_vocab.LABELS
    samples = calibration_inputs()
    if arg("--calib"):   # real augmented windows of every class (kws2_featurize.py)
        cal = np.load(arg("--calib"))
        X, y = cal["X"].astype(np.float32), cal["y"]
        rng = np.random.default_rng(0)
        pick = np.concatenate([rng.choice(np.flatnonzero(y == c), min(20, int((y == c).sum())), replace=False)
                               for c in range(len(LABELS)) if (y == c).any()])
        samples += [torch.from_numpy(X[i]).reshape(1, 49, 10, 1) for i in pick]
    print(f"[kws] {len(samples)} calibration windows")
    example = (samples[0],)
    quantizer = EthosUQuantizer(spec)
    quantizer.set_global(get_symmetric_quantization_config(is_per_channel=True))
    prepared = prepare_pt2e(torch.export.export(model, example).module(), quantizer)
    with torch.no_grad():
        for s in samples:
            prepared(s)
    quantized = convert_pt2e(prepared)

    # Float vs quantized on held-out windows (all classes) and the sample recordings.
    if arg("--calib"):
        rng = np.random.default_rng(1)
        idx = rng.choice(len(X), min(3000, len(X)), replace=False)
        with torch.no_grad():
            agree = [int(model(torch.from_numpy(X[i]).reshape(1, 49, 10, 1)).argmax()) ==
                     int(quantized(torch.from_numpy(X[i]).reshape(1, 49, 10, 1)).argmax()) for i in idx]
        print(f"[kws] int8 vs float top-1 agreement: {100 * np.mean(agree):.1f}% of {len(idx)} windows")
    with torch.no_grad():
        yes_x = torch.from_numpy(mfcc.mfcc(mfcc.read_wav(HERE / "yes.wav")[:mfcc.WINDOW])).reshape(1, 49, 10, 1)
        p = torch.softmax(quantized(yes_x).flatten(), 0)
        print(f"[kws] boot self-test clip: int8 {label(quantized(yes_x))}")
        if LABELS[int(p.argmax())] != "yes" or float(p.max()) < 0.9:
            sys.exit("[kws] the boot self-test clip is not a confident 'yes': not exporting")
    with torch.no_grad():
        for name in SAMPLES:
            wins = mfcc.windows(mfcc.read_wav(HERE / f"{name}.wav"))
            xs = [torch.from_numpy(mfcc.mfcc(w)).reshape(1, 49, 10, 1) for w in wins]
            print(f"[kws] {name}: float {[label(model(x)) for x in xs]}")
            print(f"[kws] {' ' * len(name)}  int8  {[label(quantized(x)) for x in xs]}")

    edge = to_edge_transform_and_lower(
        torch.export.export(quantized, example),
        partitioner=[EthosUPartitioner(spec)],
        compile_config=EdgeCompileConfig(_check_ir_validity=False),
    )
    pte = bytes(edge.to_executorch(ExecutorchBackendConfig(extract_delegate_segments=False)).buffer)

    rows = [", ".join(f"0x{b:02x}" for b in pte[i:i + 16]) for i in range(0, len(pte), 16)]
    name = "MicroNet-M (12 labels)" if legacy else f"KWS v2 ({len(LABELS)} labels, model/kws/kws_vocab.py)"
    guard = "#ifdef WALDO_KWS_MICRONET" if legacy else "#ifndef WALDO_KWS_MICRONET"
    suffix = "_micronet" if legacy else ""
    body = (f"#include \"kws_model.h\"\n{guard}\n"
            "__attribute__((aligned(16))) const unsigned char kws_pte[] = {\n  "
            + ",\n  ".join(rows) + "\n};\nconst unsigned long kws_pte_size = sizeof(kws_pte);\n#endif\n")
    if he:
        (HERE / f"kws_he{suffix}.pte").write_bytes(pte)
        (ROOT / "he" / f"kws_pte_he{suffix}.c").write_text(
            f"// Generated by model/kws/export_kws.py --he -- do not edit. {name} for the Ethos-U55-128.\n" + body)
        print(f"[kws] HE: {len(pte)} byte program -> he/kws_pte_he{suffix}.c")
        return
    (HERE / f"kws{suffix}.pte").write_bytes(pte)
    (ROOT / "src" / f"kws_pte{suffix}.c").write_text(
        f"// Generated by model/kws/export_kws.py -- do not edit. {name} for the Ethos-U85.\n" + body)
    (ROOT / "src" / "kws_pte.h").write_text(
        "// Generated by model/kws/export_kws.py -- do not edit.\n#pragma once\n"
        "#ifdef __cplusplus\nextern \"C\" {\n#endif\nextern const unsigned char kws_pte[];\n"
        "extern const unsigned long kws_pte_size;\n#ifdef __cplusplus\n}\n#endif\n")
    # Boot self-test data: "yes" (1 s) and its MFCCs as computed here, so the board can
    # check its own front end and the NPU result.
    yes = mfcc.read_wav(HERE / "yes.wav")[:mfcc.WINDOW]
    feats = mfcc.mfcc(yes).flatten()
    (ROOT / "src" / "test_kws.h").write_text(
        "// Generated by model/kws/export_kws.py -- do not edit.\n"
        "// Speech Commands v0.02 yes/0b40aa8e_nohash_0.wav (CC BY 4.0), and its MFCCs (mfcc.py).\n"
        "#pragma once\n#include <stdint.h>\n"
        f"static const int16_t test_kws_yes[{len(yes)}] = {{\n"
        + ",\n".join(", ".join(str(v) for v in yes[i:i + 16]) for i in range(0, len(yes), 16))
        + "};\n"
        f"static const float test_kws_yes_mfcc[{len(feats)}] = {{\n"
        + ",\n".join(", ".join(f"{v:.6g}f" for v in feats[i:i + 10]) for i in range(0, len(feats), 10))
        + "};\n")
    import re
    ops = sorted(set(re.findall(rb"(?:aten|quantized_decomposed|cortex_m)::\w+", pte)))
    print(f"[kws] {len(pte)} byte program, operators outside the NPU delegate: {[o.decode() for o in ops]}")


if __name__ == "__main__":
    main()
